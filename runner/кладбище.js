/* 5. Стрельчатая арка зала с гербом: круглые колонны с капителями, над
   острием — щит графа, с капителей свисают багровые знамёна,
   у колонн — бра со свечами. */
export function аркаСГербом() {
  const камень = [], ткань = [], золото = [], железо = [], кость = [], огни = [];
  const a = 3.75, пята = 5.6, r = 3.3, кольцо = 0.55;
  const s = new THREE.Shape();
  const cxL = -a + r, R = r + кольцо;
  const уголВнеш = Math.acos(-cxL / R), уголВнутр = Math.acos(-cxL / r);
  s.moveTo(-a - кольцо, пята);
  s.absarc(cxL, пята, R, Math.PI, уголВнеш, true);
  s.absarc(-cxL, пята, R, Math.PI - уголВнеш, 0, true);
  s.lineTo(a, пята);
  s.absarc(-cxL, пята, r, 0, Math.PI - уголВнутр, false);
  s.absarc(cxL, пята, r, уголВнутр, Math.PI, false);
  s.lineTo(-a - кольцо, пята);
  камень.push(выдавить(s, 0.75, 0.05));
  for (const sx of [-1, 1]) {
    const x = sx * (a + кольцо / 2);
    const ствол = new THREE.CylinderGeometry(0.4, 0.46, пята - 0.5, 14);
    ствол.translate(x, (пята - 0.5) / 2 + 0.35, 0);
    камень.push(ствол);
    камень.push(коробка(1.15, 0.35, 1.15, x, 0.18, 0));
    камень.push(коробка(1.1, 0.3, 1.1, x, пята - 0.05, 0));
    const капитель = new THREE.CylinderGeometry(0.58, 0.42, 0.4, 14);
    капитель.translate(x, пята - 0.38, 0);
    камень.push(капитель);
    // знамя на золотой перекладине
    золото.push(коробка(1.2, 0.07, 0.07, x, пята - 0.75, -0.62));
    const з = new THREE.Shape();
    з.moveTo(-0.5, 0); з.lineTo(0.5, 0); з.lineTo(0.5, -3.0); з.lineTo(0, -3.45); з.lineTo(-0.5, -3.0); з.lineTo(-0.5, 0);
    const знамя = new THREE.ExtrudeGeometry(з, { depth: 0.04, bevelEnabled: false });
    знамя.translate(x, пята - 0.78, -0.66);
    ткань.push(знамя);
    золото.push(коробка(0.12, 1.0, 0.03, x, пята - 2.0, -0.68));               // крест на знамени
    золото.push(коробка(0.55, 0.12, 0.03, x, пята - 1.8, -0.68));
    // бра со свечами на внутренней стороне колонны
    const xв = x - sx * 0.52;
    железо.push(коробка(0.4, 0.05, 0.05, x - sx * 0.35, 2.9, -0.1));
    железо.push(коробка(0.36, 0.05, 0.2, xв, 2.95, -0.1));
    for (const dz of [-0.1, 0.1]) {
      const свеча = new THREE.CylinderGeometry(0.045, 0.05, 0.34, 8);
      свеча.translate(xв, 3.15, -0.1 + dz);
      кость.push(свеча);
      огни.push([xв, 3.42, -0.1 + dz]);
    }
  }
  // герб над острием
  const остриё = пята + Math.sqrt(R * R - cxL * cxL);
  const щ = new THREE.Shape();
  щ.moveTo(-0.6, 0.55); щ.lineTo(0.6, 0.55); щ.lineTo(0.6, -0.1);
  щ.quadraticCurveTo(0.55, -0.6, 0, -0.85); щ.quadraticCurveTo(-0.55, -0.6, -0.6, -0.1); щ.lineTo(-0.6, 0.55);
  const щит = выдавить(щ, 0.12, 0.03);
  щит.translate(0, остриё + 0.1, -0.5);
  ткань.push(щит);
  const кайма = выдавить(щ, 0.08, 0);
  кайма.scale(1.12, 1.12, 1);
  кайма.translate(0, остриё + 0.1, -0.42);
  золото.push(кайма);
  золото.push(коробка(0.1, 0.9, 0.05, 0, остриё + 0.05, -0.6));
  золото.push(коробка(0.6, 0.1, 0.05, 0, остриё + 0.25, -0.6));
  const корона = new THREE.CylinderGeometry(0.35, 0.3, 0.22, 5);
  корона.translate(0, остриё + 0.8, -0.5);
  золото.push(корона);
  return итог({ камень, ткань, золото, железо, кость }, огни);
}

/* 6. Люстра на цепях: сводов в зале не видно — цепи уходят в темноту, под
   ними два кованых кольца в позолоте и восемнадцать свечей. */
export function люстра() {
  const золото = [], железо = [], кость = [], огни = [];
  const y = 8.2;                     // острие внизу — на 7,05 м
  for (const [rr, n, dy] of [[1.85, 12, 0], [1.1, 6, -0.25]]) {
    const кольцо = new THREE.TorusGeometry(rr, 0.07, 6, 32);
    кольцо.rotateX(Math.PI / 2);
    кольцо.translate(0, y + dy, 0);
    золото.push(кольцо);
    for (let i = 0; i < n; i++) {
      const у = (i + 0.5) / n * Math.PI * 2;
      const x = Math.cos(у) * rr, z = Math.sin(у) * rr;
      const чашка = new THREE.CylinderGeometry(0.1, 0.05, 0.08, 8);
      чашка.translate(x, y + dy + 0.08, z);
      золото.push(чашка);
      const свеча = new THREE.CylinderGeometry(0.045, 0.05, 0.3, 8);
      свеча.translate(x, y + dy + 0.27, z);
      кость.push(свеча);
      огни.push([x, y + dy + 0.52, z]);
    }
  }
  for (let i = 0; i < 6; i++) {                                                  // спицы
    const у = i / 6 * Math.PI * 2;
    железо.push(цилиндрМежду([0, y - 0.3, 0], [Math.cos(у) * 1.85, y, Math.sin(у) * 1.85], 0.04, 5));
  }
  const ствол = new THREE.CylinderGeometry(0.1, 0.16, 1.1, 10);
  ствол.translate(0, y - 0.05, 0);
  золото.push(ствол);
  const шар = new THREE.SphereGeometry(0.24, 10, 8);
  шар.translate(0, y - 0.62, 0);
  золото.push(шар);
  const остриё = new THREE.ConeGeometry(0.1, 0.35, 8);
  остриё.rotateX(Math.PI);
  остриё.translate(0, y - 0.98, 0);
  золото.push(остриё);
  for (let i = 0; i < 4; i++) {                                                  // цепи в темноту
    const у = (i + 0.5) / 4 * Math.PI * 2;
    железо.push(...цепь([Math.cos(у) * 1.85, y + 0.05, Math.sin(у) * 1.85], [0, y + 6.5, 0], 0.16));
  }
  return итог({ золото, железо, кость }, огни);
}

/* 7. Портал с витражом: колонны с пилястрами, антаблемент, над ним фронтон
   с розой — круглым окном с цветными стёклами и каменным переплётом;
   под антаблементом два подвесных фонаря. */
export function порталСВитражом() {
  const камень = [], железо = [], стёкла = [], огни = [];
  for (const sx of [-1, 1]) {
    const x = sx * 4.0;
    камень.push(коробка(1.0, 7.4, 1.0, x, 3.7, 0));
    камень.push(коробка(0.7, 6.6, 0.25, x, 3.7, -0.58));                    // пилястра
    камень.push(коробка(1.3, 0.4, 1.3, x, 0.2, 0));
    подвеснойФонарь(sx * 2.95, 7.4, 7.2, -0.25, железо, стёкла, огни);
  }
  камень.push(коробка(9.3, 0.8, 1.2, 0, 7.8, 0));
  камень.push(коробка(9.8, 0.25, 1.4, 0, 8.32, 0));
  // треугольный фронтон с круглым проёмом под розу
  const ф = new THREE.Shape();
  ф.moveTo(-3.2, 0); ф.lineTo(3.2, 0); ф.lineTo(0, 3.4); ф.lineTo(-3.2, 0);
  const проём = new THREE.Path();
  проём.absarc(0, 1.45, 1.25, 0, Math.PI * 2, true);
  ф.holes.push(проём);
  const фронтон = выдавить(ф, 0.6, 0.03);
  фронтон.translate(0, 8.44, 0.15);
  камень.push(фронтон);
  // роза: кольцо и переплёт
  const yр = 8.44 + 1.45;
  const кольцо = new THREE.TorusGeometry(1.28, 0.14, 8, 32);
  кольцо.translate(0, yр, -0.2);
  камень.push(кольцо);
  const сердце = new THREE.CylinderGeometry(0.22, 0.22, 0.25, 12);
  сердце.rotateX(Math.PI / 2);
  сердце.translate(0, yр, -0.22);
  камень.push(сердце);
  for (let i = 0; i < 8; i++) {
    const спица = коробка(2.5, 0.08, 0.14, 0, 0, 0, i / 8 * Math.PI);
    спица.translate(0, yр, -0.22);
    камень.push(спица);
  }
  // цветные стёкла — по сектору своим цветом
  const ЦВЕТА = [0xc0182c, 0x2846ff, 0xffb43a, 0x8a2be2];
  const витраж = ЦВЕТА.map(() => []);
  for (let i = 0; i < 16; i++) {
    const g = new THREE.CircleGeometry(1.22, 3, i / 16 * Math.PI * 2, Math.PI * 2 / 16);
    g.rotateY(Math.PI);                                // лицом на −z
    g.translate(0, yр, -0.1);
    витраж[i % 4].push(g);
  }
  return итог({ камень, железо, стекло: стёкла }, огни, {
    витраж: витраж.map((куски, i) => ({ сетка: склеить(куски), цвет: ЦВЕТА[i] }))
  });
}

/* 8. Балка с висячими клетками: тонкие столбы, балка в железных полосах,
   две клетки на цепях с костями узников, посередине фонарь. */
export function балкаСКлетками() {
  const камень = [], железо = [], дерево = [], кость = [], стёкла = [], огни = [];
  for (const sx of [-1, 1]) {
    const x = sx * 4.15;
    камень.push(коробка(0.75, 8.2, 0.75, x, 4.1, 0));
    камень.push(коробка(1.0, 0.3, 1.0, x, 0.15, 0));
    камень.push(коробка(1.0, 0.35, 1.0, x, 8.2, 0));
    факел(x - sx * 0.45, 3.4, -0.15, железо, огни, sx);
  }
  дерево.push(коробка(9.0, 0.5, 0.55, 0, 8.55, 0));
  железо.push(коробка(9.05, 0.07, 0.6, 0, 8.3, 0));
  железо.push(коробка(9.05, 0.07, 0.6, 0, 8.8, 0));
  for (const sx of [-1, 1]) {
    const cx = sx * 1.95, низ = 6.9, верх = 8.0, rc = 0.45;
    железо.push(...цепь([cx, 8.3, 0], [cx, верх + 0.15, 0], 0.12));
    for (const y of [низ, верх, (низ + верх) / 2]) {
      const к = new THREE.TorusGeometry(rc, 0.03, 4, 16);
      к.rotateX(Math.PI / 2);
      к.translate(cx, y, 0);
      железо.push(к);
    }
    const купол = new THREE.ConeGeometry(rc, 0.25, 12, 1, true);
    купол.translate(cx, верх + 0.12, 0);
    железо.push(купол);
    for (let i = 0; i < 10; i++) {
      const у = i / 10 * Math.PI * 2;
      железо.push(коробка(0.035, верх - низ, 0.035, cx + Math.cos(у) * rc, (низ + верх) / 2, Math.sin(у) * rc));
    }
    железо.push(коробка(rc * 1.9, 0.04, rc * 1.9, cx, низ, 0));
    // узник: череп свесился набок, рёбра, кость торчит сквозь прутья
    череп(cx + sx * 0.08, низ + 0.62, -0.05, 0.3, sx * 0.4, кость, железо);
    for (let k = 0; k < 4; k++) кость.push(коробка(0.3 - k * 0.03, 0.03, 0.2, cx, низ + 0.42 - k * 0.07, 0.05));
    кость.push(цилиндрМежду([cx - sx * 0.2, низ + 0.1, 0], [cx + sx * 0.75, низ + 0.02, -0.15], 0.035));
  }
  подвеснойФонарь(0, 8.3, 7.35, 0, железо, стёкла, огни);
  return итог({ камень, железо, дерево, кость, стекло: стёкла }, огни);
}
