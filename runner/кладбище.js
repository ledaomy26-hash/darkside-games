/* ---------- Своды подземелья и замка ----------

   До 04.10.2026 и в подземелье, и в замке над дорогой каждые 17 м стояли
   те же кладбищенские ворота. Владелец: «почему у тебя везде одни и те же
   арки… когда бежишь — одна и та же арка; сделай в подземелье что-нибудь
   другое и в замке тоже другое, что-нибудь интересненькое». Теперь у каждой
   из двух трасс по четыре своих свода, и они сменяют друг друга.

   Всё, что висит над дорогой, ниже 6,8 м не опускается в полосе |x| < 2,8:
   на крыльях бегун летит на 3,4 м, и свод не должен его задевать. Столбы
   не дальше 4,6 м от середины — там уже стоят предметы обочины.

   Каждая постройка отдаёт сетки по материалам: камень, железо, дерево,
   кость, ткань, золото; стекло — светит цветом участка, как у ворот;
   витраж — свои цвета; огни — точки живого пламени. Лицом на −z. */

function цилиндрМежду(a, b, r, грани) {
  const dx = b[0] - a[0], dy = b[1] - a[1], dz = b[2] - a[2];
  const длина = Math.hypot(dx, dy, dz);
  const g = new THREE.CylinderGeometry(r, r, длина, грани || 6);
  const ось = new THREE.Vector3(dx, dy, dz).normalize();
  g.applyQuaternion(new THREE.Quaternion().setFromUnitVectors(new THREE.Vector3(0, 1, 0), ось));
  g.translate((a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2);
  return g;
}

/* Цепь — звенья через одно повёрнутые: издали читается цепью, а не палкой. */
function цепь(a, b, звено) {
  const куски = [];
  const s = звено || 0.12;
  const длина = Math.hypot(b[0] - a[0], b[1] - a[1], b[2] - a[2]);
  const n = Math.max(1, Math.round(длина / s));
  const ось = new THREE.Vector3(b[0] - a[0], b[1] - a[1], b[2] - a[2]).normalize();
  const поворот = new THREE.Quaternion().setFromUnitVectors(new THREE.Vector3(0, 1, 0), ось);
  for (let i = 0; i < n; i++) {
    const t = (i + 0.5) / n;
    // звено стоит в плоскости xy, вытянуто по y; через одно — повёрнуто на 90° вокруг оси цепи
    const g = new THREE.TorusGeometry(s * 0.42, s * 0.09, 4, 8);
    g.scale(0.75, 1.25, 1);
    if (i % 2) g.rotateY(Math.PI / 2);
    g.applyQuaternion(поворот);
    g.translate(a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t);
    куски.push(g);
  }
  return куски;
}

/* Череп: кость отдельно, глазницы и нос — тёмным железом. s — высота черепа,
   поворот — наклон вокруг z (в арке черепа смотрят макушкой наружу). */
function череп(x, y, z, s, поворот, кость, тьма) {
  const куски = [];
  const свод = new THREE.SphereGeometry(s * 0.5, 10, 8);
  свод.scale(0.9, 0.85, 1.0);
  свод.translate(0, s * 0.08, 0);
  куски.push(свод);
  куски.push(коробка(s * 0.56, s * 0.3, s * 0.5, 0, -s * 0.3, -s * 0.16));     // челюсть
  const тёмное = [];
  for (const sx of [-1, 1]) {
    const гл = new THREE.SphereGeometry(s * 0.13, 6, 5);
    гл.translate(sx * s * 0.17, s * 0.02, -s * 0.42);
    тёмное.push(гл);
  }
  тёмное.push(коробка(s * 0.08, s * 0.12, s * 0.06, 0, -s * 0.14, -s * 0.44));
  for (const [набор, куда] of [[куски, кость], [тёмное, тьма]]) {
    for (const g of набор) {
      if (поворот) g.rotateZ(поворот);
      g.translate(x, y, z);
      куда.push(g);
    }
  }
}

/* Настенный факел: кованая чаша на кронштейне, пламя над ней. */
function факел(x, y, z, железо, огни, сторона) {
  железо.push(коробка(0.06, 0.06, 0.4, x, y - 0.1, z + 0.2));
  const чаша = new THREE.CylinderGeometry(0.16, 0.06, 0.22, 8);
  чаша.translate(x, y, z);
  железо.push(чаша);
  железо.push(цилиндрМежду([x, y - 0.11, z], [x + (сторона || 0) * 0.02, y - 0.5, z + 0.12], 0.035));
  огни.push([x, y + 0.24, z]);
}

/* Подвесной фонарь на цепи: железная клетка, стекло светит цветом участка. */
function подвеснойФонарь(x, yВерх, yФонаря, z, железо, стёкла, огни) {
  железо.push(...цепь([x, yВерх, z], [x, yФонаря + 0.36, z], 0.11));
  const крыша = new THREE.ConeGeometry(0.28, 0.26, 6);
  крыша.translate(x, yФонаря + 0.3, z);
  железо.push(крыша);
  железо.push(коробка(0.32, 0.04, 0.32, x, yФонаря - 0.22, z));
  for (const [dx, dz] of [[-1, -1], [1, -1], [-1, 1], [1, 1]]) {
    железо.push(коробка(0.03, 0.44, 0.03, x + dx * 0.14, yФонаря, z + dz * 0.14));
  }
  const стекло = new THREE.CylinderGeometry(0.13, 0.13, 0.38, 8);
  стекло.translate(x, yФонаря, z);
  стёкла.push(стекло);
  огни.push([x, yФонаря, z]);
}

function итог(наборы, огни, extra) {
  const out = { огни };
  for (const [имя, куски] of Object.entries(наборы)) if (куски.length) out[имя] = склеить(куски);
  return Object.assign(out, extra || {});
}

/* 1. Свод катакомб: полукруг из клиновидных камней разной глубины —
   кладка неровная, древняя; на замковом камне череп, по столбам факелы,
   с кольца свода свисают две цепи с черепами. */
export function сводКатакомб() {
  const камень = [], железо = [], кость = [], огни = [];
  const пята = 4.6, r = 3.75, R = 4.55;
  const n = 13;
  const р = случай(31);
  for (let i = 0; i < n; i++) {
    const угол = Math.PI - (i + 0.5) / n * Math.PI;
    const ширина = (R + r) / 2 * Math.PI / n - 0.07;
    const глубина = 0.9 + р() * 0.35;
    const блок = new THREE.BoxGeometry(R - r, ширина, глубина);
    блок.rotateZ(угол);
    блок.translate(Math.cos(угол) * (R + r) / 2, пята + Math.sin(угол) * (R + r) / 2, (р() - 0.5) * 0.12);
    камень.push(блок);
  }
  // замковый камень — выше и толще прочих
  камень.push(коробка(0.95, 1.05, 1.45, 0, пята + (R + r) / 2 + 0.1, 0));
  череп(0, пята + (R + r) / 2 + 0.05, -0.85, 0.62, 0, кость, железо);
  // столбы — кладка из блоков со сдвигом
  for (const sx of [-1, 1]) {
    const x = sx * (r + R) / 2;
    for (let k = 0, y = 0; y < пята - 0.01; k++) {
      const h = Math.min(0.62 + р() * 0.25, пята - y);
      камень.push(коробка(R - r + (k % 2 ? 0.1 : -0.04), h - 0.05, 1.05 + р() * 0.25, x + (р() - 0.5) * 0.06, y + h / 2, 0));
      y += h;
    }
    камень.push(коробка(R - r + 0.3, 0.32, 1.4, x, пята - 0.1, 0));             // пята свода
    факел(x - sx * 0.05, 3.2, -0.75, железо, огни, sx);
  }
  // цепи с черепами с кольца свода
  for (const sx of [-1, 1]) {
    const x = sx * 2.25;
    const y = пята + Math.sqrt(r * r - x * x);
    железо.push(...цепь([x, y, 0], [x, 7.35, 0], 0.13));
    череп(x, 7.15, 0, 0.36, 0, кость, железо);
  }
  return итог({ камень, железо, кость }, огни);
}

