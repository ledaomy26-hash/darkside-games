/* ---------- Кованая ограда ----------

   Секция вдоль локальной x: две поперечины и частые прутья с остриями-пиками.
   «сломанная» — часть прутьев выпала, часть погнута; «пролом» — середины
   нет вовсе, остались обломки. Случайность от номера, а не от Math.random:
   одна и та же секция при каждом запуске выглядит одинаково. */
export function секцияОграды(длина, вид) {
  const куски = [];
  const высота = 1.45, шаг = 0.13;
  const n = Math.floor(длина / шаг);
  const хеш = i => ((Math.sin(i * 12.9898 + длина * 78.233) * 43758.5453) % 1 + 1) % 1;

  const пролом = вид === 'пролом';
  for (const y of [0.22, 1.2]) {
    if (пролом) {
      куски.push(коробка(длина * 0.3, 0.035, 0.035, -длина * 0.35, y, 0));
      куски.push(коробка(длина * 0.22, 0.035, 0.035, длина * 0.39, y - 0.06, 0, 0.12));
    } else {
      куски.push(коробка(длина, 0.035, 0.035, 0, y, 0));
    }
  }
  for (let i = 0; i < n; i++) {
    const x = -длина / 2 + шаг / 2 + i * шаг;
    const r = хеш(i);
    if (пролом && Math.abs(x) < длина * 0.28) continue;
    if (вид === 'сломанная' && r < 0.22) continue;
    const наклон = вид === 'сломанная' && r > 0.85 ? (r - 0.85) * 2.4 : 0;
    const h = высота - (i % 2) * 0.08;                    // через один пониже — кованый ритм
    куски.push(коробка(0.022, h, 0.022, x, h / 2, 0, наклон));
    const пика = new THREE.ConeGeometry(0.032, 0.13, 4);
    пика.rotateZ(наклон);
    пика.translate(x - Math.sin(наклон) * h, h + 0.05, 0);
    куски.push(пика);
  }
  return склеить(куски);
}

