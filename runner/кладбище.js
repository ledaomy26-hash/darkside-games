/* Кладбище, собранное кодом: кованая ограда, каменные надгробия, готическая
   арка над дорогой, фонарные столбы.

   Зачем кодом, а не моделями. 19 сентября 2026 владелец дал свои картинки —
   ночной замок, надгробия во мху, кованые ограды — и игра переходит с
   мультяшного набора KayKit на реалистичный вид. Сложное (ангел, горгулья,
   часовня, нечисть) сделано генератором из его же картинок, а простое —
   плиты, кресты, прутья ограды — честнее и легче собрать здесь: один камень
   на всё (трипланарный, см. одетьКамень в render3d.js), железо одним цветом,
   каждая вещь — одна сетка, то есть один вызов отрисовки.

   Все вещи смотрят лицевой стороной на −z, как предметы KayKit: раскладка
   обочины поворачивает их к дороге одним и тем же правилом. Низ — на y = 0. */

import * as THREE from './vendor/three.module.js';
import { mergeGeometries } from './vendor/BufferGeometryUtils.js';

/* Склеить куски в одну сетку. У ExtrudeGeometry и BoxGeometry разный набор
   атрибутов (группы материалов), поэтому оставляем только положение и нормаль —
   развёртка камню не нужна, он кладётся по мировым осям. */
function склеить(куски) {
  const чистые = куски.map(g => {
    const n = g.index ? g.toNonIndexed() : g;
    const out = new THREE.BufferGeometry();
    out.setAttribute('position', n.getAttribute('position'));
    out.setAttribute('normal', n.getAttribute('normal'));
    return out;
  });
  const g = mergeGeometries(чистые, false);
  g.computeBoundingBox();
  g.computeBoundingSphere();
  return g;
}

function коробка(w, h, d, x, y, z, поворот) {
  const g = new THREE.BoxGeometry(w, h, d);
  if (поворот) g.rotateZ(поворот);
  g.translate(x, y, z);
  return g;
}

/* Плоская фигура, выдавленная в толщину, лицом на −z, низом на ноль. */
function выдавить(shape, толщина, фаска) {
  const g = new THREE.ExtrudeGeometry(shape, {
    depth: толщина, bevelEnabled: !!фаска, bevelThickness: фаска || 0,
    bevelSize: фаска || 0, bevelSegments: 2, curveSegments: 14
  });
  g.translate(0, 0, -толщина / 2);
  return g;
}

/* ---------- Надгробия ----------

   Виды — с картинок владельца: плита со скруглённым верхом, готическая
   стрельчатая плита, латинский крест, кельтский крест с кольцом, обелиск.
   Под каждым низкий цоколь: без него камень выглядит воткнутым в землю. */
export function надгробие(вид) {
  const куски = [];
  const цоколь = (w, d) => куски.push(коробка(w, 0.14, d, 0, 0.07, 0));

  if (вид === 'плита') {
    const s = new THREE.Shape();
    s.moveTo(-0.36, 0.1); s.lineTo(0.36, 0.1); s.lineTo(0.36, 0.72);
    s.absarc(0, 0.72, 0.36, 0, Math.PI, false);
    s.lineTo(-0.36, 0.1);
    куски.push(выдавить(s, 0.14, 0.025));
    цоколь(0.92, 0.36);
  } else if (вид === 'готика') {
    /* Стрельчатый верх: две дуги, сходящиеся остриём. */
    const s = new THREE.Shape();
    const a = 0.4, пята = 0.78, r = 0.62;
    s.moveTo(-a, 0.1); s.lineTo(a, 0.1); s.lineTo(a, пята);
    s.absarc(a - r, пята, r, 0, Math.acos((r - a) / r), false);
    const вершина = Math.sqrt(r * r - (r - a) * (r - a));
    s.lineTo(0, пята + вершина);
    s.absarc(-a + r, пята, r, Math.PI - Math.acos((r - a) / r), Math.PI, false);
    s.lineTo(-a, 0.1);
    куски.push(выдавить(s, 0.16, 0.03));
    цоколь(1.0, 0.4);
  } else if (вид === 'крест') {
    куски.push(коробка(0.16, 1.25, 0.14, 0, 0.1 + 0.625, 0));
    куски.push(коробка(0.66, 0.16, 0.14, 0, 0.98, 0));
    куски.push(коробка(0.42, 0.22, 0.34, 0, 0.21, 0));      // ступень
    цоколь(0.62, 0.46);
  } else if (вид === 'кельтский') {
    куски.push(коробка(0.18, 1.35, 0.15, 0, 0.1 + 0.675, 0));
    куски.push(коробка(0.72, 0.18, 0.15, 0, 1.06, 0));
    const кольцо = new THREE.TorusGeometry(0.24, 0.045, 6, 20);
    кольцо.translate(0, 1.06, 0);
    куски.push(кольцо);
    куски.push(коробка(0.46, 0.26, 0.36, 0, 0.23, 0));
    цоколь(0.66, 0.5);
  } else {                                                 // обелиск
    const ствол = new THREE.CylinderGeometry(0.16, 0.24, 1.7, 4, 1);
    ствол.rotateY(Math.PI / 4);
    ствол.translate(0, 0.36 + 0.85, 0);
    куски.push(ствол);
    const верх = new THREE.ConeGeometry(0.2, 0.28, 4);
    верх.rotateY(Math.PI / 4);
    верх.translate(0, 0.36 + 1.7 + 0.14, 0);
    куски.push(верх);
    куски.push(коробка(0.56, 0.22, 0.56, 0, 0.25, 0));
    цоколь(0.74, 0.74);
  }
  return склеить(куски);
}

