/* 3. Арка из черепов — оссуарий: каменное кольцо, по нему черепа макушкой
   наружу, столбы облицованы черепами, над замком — скрещённые кости,
   на столбах свечи. */
export function аркаИзЧерепов() {
  const камень = [], кость = [], железо = [], огни = [];
  const пята = 4.6, r = 3.95;
  const n = 19;
  for (let i = 0; i < n; i++) {
    const угол = Math.PI - i / (n - 1) * Math.PI;
    const блок = new THREE.BoxGeometry(0.7, r * Math.PI / (n - 1) + 0.02, 0.7);
    блок.rotateZ(угол);
    блок.translate(Math.cos(угол) * (r + 0.32), пята + Math.sin(угол) * (r + 0.32), 0.12);
    камень.push(блок);
    череп(Math.cos(угол) * r, пята + Math.sin(угол) * r, -0.3, 0.52, угол - Math.PI / 2, кость, железо);
  }
  for (const sx of [-1, 1]) {
    const x = sx * 4.1;
    камень.push(коробка(0.9, пята, 1.0, x, пята / 2, 0.1));
    for (let k = 0; k < 6; k++) {
      череп(x - sx * 0.05, 0.55 + k * 0.7, -0.48, 0.5, 0, кость, железо);
    }
    камень.push(коробка(1.1, 0.25, 1.1, x, пята + 0.05, 0.1));                 // капитель со свечами
    for (const [dx, h] of [[-0.25, 0.42], [0.05, 0.6], [0.3, 0.36]]) {
      const свеча = new THREE.CylinderGeometry(0.06, 0.07, h, 8);
      свеча.translate(x + dx, пята + 0.18 + h / 2, -0.25);
      кость.push(свеча);
      огни.push([x + dx, пята + 0.3 + h, -0.25]);
    }
  }
  // скрещённые кости над вершиной
  const yК = пята + r + 0.95;
  for (const s of [-1, 1]) {
    кость.push(цилиндрМежду([-0.75 * s, yК - 0.55, -0.35], [0.75 * s, yК + 0.55, -0.35], 0.09));
    for (const [px, py] of [[-0.75 * s, yК - 0.55], [0.75 * s, yК + 0.55]]) {
      const шиш = new THREE.SphereGeometry(0.14, 6, 5);
      шиш.translate(px, py, -0.35);
      кость.push(шиш);
    }
  }
  череп(0, yК, -0.5, 0.72, 0, кость, железо);
  return итог({ камень, кость, железо }, огни);
}

