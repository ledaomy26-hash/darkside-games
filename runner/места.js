/* Местности: по какой трассе бежим.

   Владелец 23.09.2026: «бесконечно бежать по одной трассе скучно, надо
   разбить. Основная трасса — вот эта. И дополнительные: открываются после
   прохождения этой, или за набранные очки, или можно купить».

   С 29.09.2026 по его слову — как в Subway Surfers: главная трасса одна,
   кладбище, бежишь по ней сколько угодно. Остальные только покупаются —
   монетами и кристаллами вместе («не просто же так мы собираем кристаллы
   и монеты») или сразу за рубли. Открытие за пробежанные метры убрано.

   Здесь только описание местностей и правило открытия. Как местность выглядит
   на дороге — в render3d.js (МЕСТНОСТИ), кто на ней стоит — в engine.js
   (ТВАРИ_МЕСТ). Так новая местность заводится в одном месте, а проверить
   условия можно в Node без браузера. */
(function (root, factory) {
  const api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.RunnerPlaces = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /* `цена` — монеты и кристаллы, которые списываются вместе; `рубли` — цена
     покупки за деньги. За рубли можно купить только в приложении (RuStore):
     на сайте платить нечем, там цена в рублях только показывается.
     Цифры назвал владелец 29.09.2026. У первой местности цены нет. */
  const МЕСТА = [
    {
      id: 'кладбище', имя: 'Кладбище', цена: null, рубли: 0,
      о: 'Ночное кладбище под полной луной. Отсюда всё началось.'
    },
    {
      id: 'подземелье', имя: 'Подземелье', цена: { coins: 20000, gems: 250 }, рубли: 2000,
      о: 'Катакомбы под кладбищем: своды, факелы, кости в нишах.'
    },
    {
      id: 'замок', имя: 'Замок', цена: { coins: 25000, gems: 300 }, рубли: 3000,
      о: 'Залы графа: доспехи, привидения, ожившие статуи.', скоро: true
    }
  ];

  const местоПо = id => МЕСТА.find(м => м.id === id) || МЕСТА[0];

  /* Открыта ли местность: бесплатная — всегда, остальные — если куплены. */
  function открыто(save, м) {
    if (!м.цена) return true;
    return Array.isArray(save.места) && save.места.includes(м.id);
  }

  /* На какой местности бежим: выбранная, если она открыта, иначе первая.
     Проверять надо каждый раз: местность могла быть выбрана, а запись потом
     подчищена. `сБудущими` — на тестовой ссылке владельца (30.09.2026) можно
     бежать и по трассе «скоро», чтобы посмотреть её раньше игроков. */
  function текущее(save, сБудущими) {
    const м = местоПо(save && save.место);
    return открыто(save || {}, м) && (!м.скоро || сБудущими) ? м : МЕСТА[0];
  }

  return { МЕСТА, местоПо, открыто, текущее };
});
