/* Лавка: обличья бегуна и снаряжение, которое покупается за находки.

   Здесь только описания и счёт цен — ни разметки, ни сохранения. Так список
   товаров правится в одном месте, а проверить цены можно в Node.

   Две валюты разного веса: монеты сыплются под ноги, кристаллы попадаются
   редко. С 29.09.2026 каждая вещь стоит и того, и другого сразу — владелец:
   «не монеты или кристаллы, а монеты и кристаллы, не просто же так мы
   собираем и то, и другое». */
(function (root, factory) {
  const api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.RunnerShop = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /* ---------- Цена: монеты и кристаллы вместе ----------

     Доля кристаллов в цене — такая же, в какой они выпадают. Замер 29.09.2026:
     бот без ошибок, по 40 забегов на 1, 3 и 10 км — в кошелёк приходит 126–129
     монет (вместе с монетами за метры) на один подобранный кристалл. Поэтому
     кристаллов в цене — монеты, делённые на 128: пока набираешь монеты на
     вещь, набираются и кристаллы, и путь к покупке не удлиняется.

     Вещи, что прежде продавались только за кристаллы, пересчитаны по тому же
     курсу в монеты: 12 кристаллов ≈ 1500 монет, 30 ≈ 3800. */
  const МОНЕТ_НА_КРИСТАЛЛ = 128;

  function цена(монеты) {
    return { coins: монеты, gems: монеты ? Math.max(1, Math.round(монеты / МОНЕТ_НА_КРИСТАЛЛ)) : 0 };
  }

  /* Обличья различаются цветом плаща и тела: бегун рисуется кодом, поэтому
     новое обличье — это несколько чисел, а не рисунок. */
  const SKINS = [
    {
      id: 'runner', name: 'Беглец', cost: цена(0),
      about: 'Тот, кто просто хочет добежать до рассвета.',
      colors: { body: '#e6e9f5', trim: '#8b5cf6' }
    },
    {
      id: 'gravedigger', name: 'Могильщик', cost: цена(800),
      about: 'Знает тут каждую плиту. Плиты его тоже знают.',
      colors: { body: '#b8c0d8', trim: '#22d3ee' }
    },
    {
      id: 'plague', name: 'Чумной доктор', cost: цена(2200),
      about: 'Клюв набит травами. Помогает от запаха, не от нечисти.',
      colors: { body: '#d9cfa8', trim: '#65e06a' }
    },
    {
      id: 'ghost', name: 'Неупокоенный', cost: цена(5000),
      about: 'Бежит по привычке: спешить ему, вообще-то, уже некуда.',
      colors: { body: '#a8d8ff', trim: '#4b6ef5' }
    },
    {
      id: 'hunter', name: 'Охотник', cost: цена(9000),
      about: 'Пришёл сюда сам. Это его и подвело.',
      colors: { body: '#f0d9a0', trim: '#f43f5e' }
    },
    {
      id: 'vampire', name: 'Кровопийца', cost: цена(1500),
      about: 'Свои за своим не гонятся. Но эти — гонятся.',
      colors: { body: '#2b1b2e', trim: '#f43f5e' }
    },
    {
      id: 'bones', name: 'Костяной', cost: цена(3800),
      about: 'Терять больше нечего, поэтому бежит легко.',
      colors: { body: '#e8e4d8', trim: '#22d3ee' }
    }
  ];

  /* Снаряжение — это уровни, продлевающие действие находок. Пятый уровень
     удваивает то, что даёт первая подобранная вещь. */
  const UPGRADES = [
    {
      id: 'magnet', name: 'Магнит', max: 5,
      about: 'Дольше притягивает монеты со всех дорожек.'
    },
    {
      id: 'shield', name: 'Оберег', max: 5,
      about: 'Дольше держится щит, который гасит один удар.'
    },
    {
      id: 'dash', name: 'Молния', max: 5,
      about: 'Дольше длится рывок: быстрее, неуязвим, сносит мертвецов.'
    },
    {
      id: 'wings', name: 'Крыло', max: 5,
      about: 'Дольше держит в воздухе над всей этой нечистью.'
    }
  ];

  /* Отдельная покупка на один раз: щит уже в начале забега. */
  const CHARM = {
    id: 'startShield', name: 'Ладанка', cost: цена(6000),
    about: 'Забег начинается со щитом. Покупается один раз.'
  };

  const UPGRADE_BASE = 400;

  /* Каждый следующий уровень вдвое дороже предыдущего: 400, 800, 1600…
     Это монетная часть; кристаллы к ней — upgradeCost. */
  function upgradePrice(level) {
    return UPGRADE_BASE * Math.pow(2, level);
  }

  function upgradeCost(level) {
    return цена(upgradePrice(level));
  }

  function skinById(id) {
    return SKINS.find(s => s.id === id) || SKINS[0];
  }

  /* Хватает ли средств на цену { coins, gems }. Возвращает причину отказа,
     а не голое «нет»: этот же текст показывается в лавке, чтобы покупатель
     понимал, чего ему не хватает — монет, кристаллов или того и другого. */
  function canAfford(purse, cost) {
    const нетМонет = Math.max(0, (cost.coins || 0) - (purse.coins || 0));
    const нетКристаллов = Math.max(0, (cost.gems || 0) - (purse.gems || 0));
    if (!нетМонет && !нетКристаллов) return { ok: true };
    const части = [];
    if (нетМонет) части.push(`${нетМонет} ${plural(нетМонет, 'монеты', 'монет', 'монет')}`);
    if (нетКристаллов) части.push(`${нетКристаллов} ${plural(нетКристаллов, 'кристалла', 'кристаллов', 'кристаллов')}`);
    return {
      ok: false,
      short: { coins: нетМонет, gems: нетКристаллов },
      reason: `Не хватает ${части.join(' и ')}`
    };
  }

  /* Списать цену с кошелька. Зовётся только после canAfford. */
  function pay(purse, cost) {
    purse.coins = (purse.coins || 0) - (cost.coins || 0);
    purse.gems = (purse.gems || 0) - (cost.gems || 0);
  }

  /* Русские числительные: 1 монета, 2 монеты, 5 монет. */
  function plural(n, one, few, many) {
    const mod10 = n % 10, mod100 = n % 100;
    if (mod10 === 1 && mod100 !== 11) return one;
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
    return many;
  }

  return {
    SKINS, UPGRADES, CHARM, МОНЕТ_НА_КРИСТАЛЛ,
    цена, upgradePrice, upgradeCost, skinById, canAfford, pay, plural
  };
});
